/**
 * @brief A header file with declaration for ModelInference Class
 * @file model_inference.hpp
 */
#ifndef OPENVINO_WRAPPER_LIB__INFERENCES__MODEL_INFERENCE_HPP_
#define OPENVINO_WRAPPER_LIB__INFERENCES__MODEL_INFERENCE_HPP_
#include <memory>
#include <string>
#include <vector>
#include "openvino_wrapper_lib/inferences/base_inference.hpp"
#include "opencv2/opencv.hpp"

namespace openvino_wrapper_lib
{
/**
 * @class ModelInference
 * @brief Inference whose frame pre-processing and result decoding are done by its model class.
 * ModelT provides enqueue(engine, frame, location) and fetchResults(engine, results, threshold).
 * The supported combinations of ModelT and ResultT are instantiated in model_inference.cpp.
 */
template <typename ModelT, typename ResultT>
class ModelInference : public BaseInference
{
public:
  explicit ModelInference(double show_output_thresh);
  /**
   * @brief Load the model.
   */
  void loadNetwork(std::shared_ptr<ModelT> network);
  /**
   * @brief Enqueue a frame to this class.
   * The frame will be buffered but not inferred yet.
   * @param[in] frame The frame to be enqueued.
   * @param[in] input_frame_loc The location of the enqueued frame with respect
   * to the frame generated by the input device.
   * @return Whether this operation is successful.
   */
  bool enqueue(const cv::Mat& frame, const cv::Rect& input_frame_loc) override;
  /**
   * @brief This function will fetch the results of the previous inference and
   * stores the results in a result buffer array. All buffered frames will be
   * cleared.
   * @return Whether the Inference object fetches a result this time
   */
  bool fetchResults() override;
  /**
   * @brief Get the length of the buffer result array.
   * @return The length of the buffer result array.
   */
  int getResultsLength() const override;
  /**
   * @brief Get the location of result with respect
   * to the frame generated by the input device.
   * @param[in] idx The index of the result.
   */
  const openvino_wrapper_lib::Result* getLocationResult(int idx) const override;
  /**
   * @brief Show the observed result either through image window or ROS topic.
   */
  void observeOutput(const std::shared_ptr<Outputs::BaseOutput>& output) override;
  /**
   * @brief Get the name of the Inference instance.
   * @return The name of the Inference instance.
   */
  const std::string getName() const override;
  const std::vector<cv::Rect> getFilteredROIs(const std::string filter_conditions) const override;

private:
  std::shared_ptr<ModelT> valid_model_;
  std::vector<ResultT> results_;
  double show_output_thresh_ = 0;
};
}  // namespace openvino_wrapper_lib
#endif  // OPENVINO_WRAPPER_LIB__INFERENCES__MODEL_INFERENCE_HPP_
